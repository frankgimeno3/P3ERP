import assert from 'node:assert/strict';
import {createFlatplan,mutateFlatplan,validateFlatplan,flatplanRows,flatplanPageLabel,flatplanMagazinePageLabel,alignFlatplan} from '../app/lib/preliminaryFlatplan.js';
import {flatplanSources} from '../server/features/produccion/PreliminaryFlatplanRepository.js';
const a={id:'a',account:'A',type:'Contenido',detail:'Doble',pages:2};
const b={id:'b',account:'B',type:'Artículo',detail:'Triple',pages:3};
let plan=createFlatplan([a,b]);
assert.equal(plan.slots[0],'cover');assert.ok(!plan.slots.includes('back'));assert.equal(plan.slots.length%2,0);
assert.ok(!plan.blocks.some(b=>b.type==='Contraportada'));
const singleBlock=id=>({id,account:id,type:'Anuncio',detail:id,pages:1});
const cascadePlan={slots:['cover','inside',null,'d','d','x','y',null,null,'e','e','z',null,null],blocks:[{id:'cover',type:'Portada'},{id:'inside',type:'Interior portada'},{id:'d',type:'Anuncio',pages:2},{id:'e',type:'Artículo',pages:2},...['x','y','z'].map(singleBlock)],excluded:[]};
validateFlatplan(cascadePlan);
const swapped=mutateFlatplan(cascadePlan,{type:'swap',blockId:'x',otherId:'y'});
assert.equal(swapped.slots[5],'y');assert.equal(swapped.slots[6],'x');
assert.equal(swapped.slots.filter((id,i)=>id!==cascadePlan.slots[i]).length,2,'Swap changes exactly two positions');
assert.throws(()=>mutateFlatplan(cascadePlan,{type:'swap',blockId:'d',otherId:'x'}),/una página/);
const cascade=mutateFlatplan(cascadePlan,{type:'remove-empty',target:2});
assert.equal(cascade.slots[2],'x');assert.equal(cascade.slots[5],'y');assert.equal(cascade.slots[6],'z');assert.equal(cascade.slots.length,12);
for(const index of [3,4,9,10])assert.equal(cascade.slots[index],cascadePlan.slots[index],'Multi-page blocks stay in their exact positions');
const brought=mutateFlatplan(cascadePlan,{type:'fill-hole',blockId:'x',target:7,compact:false});
assert.equal(brought.slots[7],'x');assert.equal(brought.slots[5],null);assert.equal(brought.slots[6],'y');assert.equal(brought.slots.length,14);
const broughtCompact=mutateFlatplan(cascadePlan,{type:'fill-hole',blockId:'x',target:7,compact:true});assert.equal(broughtCompact.slots[7],'x');assert.equal(broughtCompact.slots[5],'y');
const pairBrought=mutateFlatplan(cascadePlan,{type:'fill-hole',blockId:'d',target:7,compact:false});assert.deepEqual(pairBrought.slots.slice(7,9),['d','d']);assert.equal(pairBrought.slots[3],null);assert.equal(pairBrought.slots[4],null);
assert.throws(()=>mutateFlatplan(cascadePlan,{type:'fill-hole',blockId:'d',target:8}),/revista par/);
assert.throws(()=>mutateFlatplan(cascadePlan,{type:'fill-hole',blockId:'d',target:2}),/revista par|libres/);
const previous=structuredClone(plan);previous.blocks.push({id:'back',type:'Contraportada',pages:1});previous.slots[previous.slots.length-1]='back';
const withoutBack=alignFlatplan(previous);assert.ok(!withoutBack.slots.includes('back'));assert.ok(!withoutBack.blocks.some(b=>b.id==='back'));
assert.equal(plan.slots[4],'summary');assert.equal(plan.slots[6],'index');
assert.equal(flatplanPageLabel(0),'Portada');assert.equal(flatplanPageLabel(1),'Interior portada');
assert.equal(flatplanPageLabel(2),'1');assert.equal(flatplanPageLabel(3),'2');
assert.equal(flatplanPageLabel(4),'3');assert.equal(flatplanPageLabel(6),'5');
assert.equal(flatplanMagazinePageLabel(4),'3');assert.equal(flatplanMagazinePageLabel(6),'5');
const double={...a,id:'double',type:'Anuncio'};
let spread=createFlatplan([double]);
assert.equal(spread.slots[4],'summary');assert.equal(spread.slots[6],'index','Initial alignment keeps reserved pages in place');
let start=spread.slots.indexOf('double');assert.equal((start+1)%2,0);assert.equal(spread.slots[start+1],'double');
assert.throws(()=>mutateFlatplan(spread,{type:'move',blockId:'double',target:2}),/revista par/);
spread=mutateFlatplan(spread,{type:'insert-empty',target:2});
start=spread.slots.indexOf('double');assert.equal((start+1)%2,0);validateFlatplan(spread);
const legacy=createFlatplan([]);legacy.blocks.push(double);legacy.slots[2]='double';legacy.slots[3]='double';
assert.throws(()=>validateFlatplan(legacy),/física par/);
const corrected=alignFlatplan(legacy);assert.equal((corrected.slots.indexOf('double')+1)%2,0);
const articleLegacy=createFlatplan([]);articleLegacy.blocks.push({...double,id:'sparklike',type:'Artículo'});articleLegacy.slots[2]='sparklike';articleLegacy.slots[3]='sparklike';
const articleAligned=alignFlatplan(articleLegacy);
assert.deepEqual(flatplanRows(articleAligned).filter(r=>r.block?.id==='sparklike').map(r=>[r.label,r.part,r.total]),[['2',1,2],['3',2,2]]);
const vacant=createFlatplan([]);vacant.slots.splice(3,0,null,null);
const inHole=mutateFlatplan(vacant,{type:'add',block:double,count:2,target:3});
assert.equal(inHole.slots.length,vacant.slots.length);assert.equal(inHole.slots.indexOf('summary'),vacant.slots.indexOf('summary'));
assert.deepEqual(flatplanRows(plan).filter(r=>r.block?.id==='a').map(r=>[r.part,r.total]),[[1,2],[2,2]]);
const frozen=JSON.stringify(plan);const bStart=plan.slots.indexOf('b');
assert.throws(()=>mutateFlatplan(plan,{type:'move',blockId:'a',target:bStart+1}),/parte intermedia/);
assert.throws(()=>mutateFlatplan(plan,{type:'insert-empty',target:bStart+1}),/parte intermedia/);
assert.throws(()=>mutateFlatplan(plan,{type:'remove',blockId:'cover'}),/portada/);
assert.equal(JSON.stringify(plan),frozen);
const shifted=mutateFlatplan(plan,{type:'move',blockId:'a',target:bStart});
assert.deepEqual(shifted.slots.slice(bStart,bStart+5),['a','a','b','b','b']);
assert.equal(shifted.slots[2],null);assert.equal(shifted.slots[3],null);
const removed=mutateFlatplan(plan,{type:'remove',blockId:'a',compact:false});
assert.equal(removed.slots.length,plan.slots.length);assert.equal(removed.slots[2],null);assert.equal(removed.slots[3],null);
assert.equal(removed.slots.indexOf('b'),bStart);
const filled=mutateFlatplan(removed,{type:'move',blockId:'b',target:2});
assert.equal(filled.slots.length,removed.slots.length+4,'Insufficient free run inserts all three pages and pads parity');
const single=mutateFlatplan(removed,{type:'add',block:{...a,id:'c'},count:2,target:2});
assert.equal(single.slots.length,removed.slots.length);assert.equal(single.slots.indexOf('b'),bStart,'A sufficient hole does not shift subsequent contents');
const compact=mutateFlatplan(plan,{type:'remove',blockId:'a',compact:true});
assert.equal(compact.slots.indexOf('b'),bStart-2);assert.equal(compact.slots.length,plan.slots.length-2);
assert.equal(mutateFlatplan(plan,{type:'remove',blockId:'b',compact:true}).slots.length%2,0);
const resized=mutateFlatplan(plan,{type:'resize',blockId:'a',count:4});assert.equal(resized.slots.filter(id=>id==='a').length,4);validateFlatplan(resized);
const source={id_contenido:'one',especificaciones_contenido:'2PAGS',cliente_hoja:'Cuenta',pagina_hoja:'P24+27',datos_importacion:{fila:3},materiales:[]};
const sources=flatplanSources([{...source,tipo:'anuncios'},{...source,tipo:'articulos'}]);assert.equal(sources.length,1,'Sheet status columns must not duplicate an advertisement as an article');assert.equal(sources[0].pages,2);assert.equal(sources[0].arrival,null);
assert.equal(flatplanSources([{...source,especificaciones_contenido:'1PAG+ART'}]).length,2);
assert.deepEqual(flatplanSources([{...source,especificaciones_contenido:'PAG+ART',pagina_hoja:'P.32+56+57'}]).map(s=>s.pages),[1,2]);
assert.equal(flatplanSources([], [{id:'29',empresa:'Redacción',titulo:'Sin ficha de contenido',paginas:'3'}])[0].pages,3,'Editorial rows without a production ID must be included');
assert.equal(flatplanSources([{...source,especificaciones_contenido:'ARTICULO'}],[{id_contenido:'one',paginas:'3',titulo:'Artículo'}])[0].pages,3);
// Repeated mutations exercise preservation of all remaining content units.
for(let n=0;n<100;n++) {
 let p=createFlatplan([a,b]);
 p=mutateFlatplan(p,{type:'insert-empty',target:2});
 p=mutateFlatplan(p,{type:'move',blockId:'a',target:p.slots.indexOf('b')});
 p=mutateFlatplan(p,{type:'resize',blockId:'b',count:n%5+1});
 p=mutateFlatplan(p,{type:'remove',blockId:'a',compact:n%2===0});
 validateFlatplan(p);assert.equal(p.slots.filter(id=>id==='b').length,n%5+1);
}
console.log('PASS: indivisible blocks, destination boundaries, holes, insertion, both removals, resizing, parity, covers, numbering and source deduplication.');
