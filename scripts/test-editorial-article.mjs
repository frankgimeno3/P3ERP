import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import env from '@next/env';
import {getPgPool} from '../server/database/pgClient.js';
import {createArticle} from '../server/features/controlRedaccion/ControlRedaccionRepository.js';
import {validateArticle} from '../app/config/editorialArticle.js';
env.loadEnvConfig(process.cwd());
const pool=getPgPool(),db=await pool.connect(),schema='test_article_'+randomUUID().replaceAll('-','');
const data={empresa:'Empresa prueba',titulo:'Artículo prueba',estado:'Pendiente',responsable_correccion:'Frank',revista:'',paginas:'2',espana_previsto_numero:'123',estado_publicacion_vidrioperfil:false};
try{
 await db.query('CREATE SCHEMA '+schema);await db.query('SET search_path TO '+schema+',public');
 await db.query('CREATE TABLE '+schema+'.produccion_control_redaccion (LIKE public.produccion_control_redaccion INCLUDING ALL)');
 await db.query('CREATE TABLE '+schema+'.produccion_contenidos (LIKE public.produccion_contenidos INCLUDING ALL)');
 await db.query('ALTER TABLE produccion_control_redaccion ALTER COLUMN id DROP DEFAULT');
 await db.query('ALTER TABLE produccion_control_redaccion ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY');
 assert.throws(()=>validateArticle({...data,espana_previsto_numero:''}),/al menos/);
 assert.throws(()=>validateArticle({...data,responsable_correccion:'Otro'}),/responsable/);
 assert.throws(()=>validateArticle({...data,estado:'Inventado'}),/estado/);
 assert.throws(()=>validateArticle({...data,paginas:'0'}),/páginas/);
 for(const key of ['espana_previsto_numero','latam_previsto_numero','especial_numero','hueco_previsto'])assert(validateArticle({...data,espana_previsto_numero:'',[key]:'1'}));
 const row=await createArticle(data,db);assert.equal(row.revista,'');assert.equal(row.estado_publicacion_vidrioperfil,'No');
 const published=await createArticle({...data,revista:'Vidrio',estado_publicacion_vidrioperfil:true},db);assert.equal(published.estado_publicacion_vidrioperfil,'Sí');
 assert.equal((await db.query('SELECT count(*)::int n FROM produccion_control_redaccion')).rows[0].n,2);
 assert.equal((await db.query('SELECT count(*)::int n FROM produccion_contenidos WHERE tipo_contenido=\'articulo\'')).rows[0].n,2);
 console.log('PASS: article creation against isolated RDS schema, optional magazine, all placement alternatives, checkbox persistence and invalid inputs.');
}finally{await db.query('SET search_path TO public');await db.query('DROP SCHEMA IF EXISTS '+schema+' CASCADE');db.release();await pool.end();}
