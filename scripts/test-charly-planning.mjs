import assert from 'node:assert/strict';
import {buildCharlyPlanning} from '../app/lib/charlyPlanning.js';
import {validateLayoutEntry} from '../app/lib/magazineLayout.js';
const row=(id,company,extra={})=>({id_contenido:id,tipo:'articulos',nombre_empresa:company,estado_contenido:'Pendiente de gestionar Charly',...extra});
const rows=buildCharlyPlanning([row('b','Zulu'),row('a','Alfa'),row('c','Beta',{posicion_revista:3,paginas_ocupadas:1}),row('d','Digital',{formato_revista:'digital'})],'impresa');
assert.deepEqual(rows.map(r=>r.id_contenido),['c','a','b']);
assert.equal(rows[1].planning.posicion,1);
assert.equal(rows[2].planning.posicion,2);
assert(rows[1].provisional);
const long=buildCharlyPlanning([row('long','A',{paginas_ocupadas:3})],'digital');
assert.equal(long[0].planning.posicion,1);
const occupied=buildCharlyPlanning([row('long','A',{paginas_ocupadas:4})],'digital');
assert.equal(occupied[0].planning.posicion,7);
const final=buildCharlyPlanning([row('a','A',{estado_contenido:'Material OK - pendiente de publicar'})],'digital',[{id_contenido:'a',tipo:'articulos',posicion:9,paginas:2,seccion:'Especial'}]);
assert.equal(final[0].planning.posicion,9);assert.equal(final[0].provisional,false);
assert.throws(()=>validateLayoutEntry({id_contenido:'a',tipo:'articulos',posicion:3,paginas:2,seccion:'Noticias',id_material:'pdf'}),/reservadas/);
const obsolete=buildCharlyPlanning([row('a','A')],'digital',[{id_contenido:'a',tipo:'articulos',posicion:9,paginas:2,seccion:'Especial'}]);
assert.equal(obsolete[0].planning.posicion,1,'Una asignación final antigua no sustituye la planificación al volver a fase 3');
console.log('Charly: orden, soportes, reservas, propuestas y prioridad final correctos.');
